#!/usr/bin/env node
// =============================================================================
// generate-qa-checklist.mjs — catalog → docs/QA-CHECKLIST.md
// =============================================================================
// Renders the Phase 4 QA pass as a per-rule trigger/expectation checklist so
// verification is checkbox work, not archaeology. Generated from the same
// catalogs as the blueprint — re-generate whenever the catalog changes; never
// hand-edit the output.
// =============================================================================

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');

const events = JSON.parse(await readFile(join(ROOT, 'catalog', 'events-catalog.json'), 'utf8'));
const property = JSON.parse(await readFile(join(ROOT, 'catalog', 'property.json'), 'utf8'));

const pv = events.pageView;
const se = events.siteError;
const nt = events.newsletterTest && events.newsletterTest.enabled ? events.newsletterTest : null;
const edgeDomain = property.webSdkInstance.edgeDomain;

const evList = (specEvents) =>
  (specEvents || [])
    .filter((e) => !e.valueFrom) // valued events are deferred (see catalog notes)
    .map((e) => e.event)
    .join(', ') || '—';
const eVarList = (eVars) =>
  Object.entries(eVars || {})
    .map(([k, de]) => `${k}←%${de}%`)
    .join(' · ') || '—';

const L = [];
L.push('# QA Checklist — AboutAmazon-US (WebSDK)');
L.push('');
L.push('GENERATED by scripts/generate-qa-checklist.mjs — do not hand-edit; change the catalog and re-generate.');
L.push('');
L.push('**Setup:** fresh incognito session · page pointed at the **Development** embed code ·');
L.push('[Adobe Experience Platform Debugger](https://experienceleague.adobe.com/en/docs/experience-platform/debugger/home) or an Assurance session attached · Network tab filtered to `interact`.');
L.push('Simulated triggers (`adobeDataLayer.push(...)`) prove the RULE wiring; real site actions also prove the DATA');
L.push('(the payload data elements read fields that arrive alongside the push). Do the bulk with pushes, spot-check with real actions.');
L.push('');
L.push('## 0. Every page, before anything else');
L.push('');
L.push('- [ ] Exactly **ONE** `interact` call to the edge per page view — no second personalization call, no second page-view call');
L.push(`- [ ] The call goes to \`https://${edgeDomain}/ee/...\` (first-party edge domain)`);
L.push('- [ ] Zero requests to `/b/ss/` (classic AppMeasurement) and zero to `tt.omtrdc.net` (at.js) — Findings 1/3');
L.push('- [ ] Dev embed routes to report suite `aboutamzndev` (datastream-level — Finding 2 retirement evidence)');
L.push('- [ ] Page-view request carries `renderDecisions: true`' + (nt ? ` and \`decisionScopes: ["${nt.scope}"]\`` : ''));
L.push('');
L.push(`## 1. Page view — \`${pv.rule}\``);
L.push('');
L.push(`- [ ] Trigger: any page load (data layer pushes \`${pv.acdlEvent}\`)`);
L.push(`- [ ] \`data.__adobe.analytics\` carries: events \`${evList(pv.analytics.events)}\` · pageName/channel/campaign populated`);
L.push(`- [ ] eVars present when their source has a value: ${Object.keys(pv.analytics.eVars || {}).length} mapped · props: ${Object.keys(pv.analytics.props || {}).length} mapped · lists: ${Object.keys(pv.analytics.lists || {}).length} mapped (spot-check 3 of each against the OLD property's beacon for the same URL)`);
L.push('- [ ] `event4` is ABSENT (deferred until the icid decision — parity with the old property, where it never fired)');
L.push('');
L.push('## 2. Interactions (one row at a time)');
L.push('');
L.push('For each: perform the site action (or `adobeDataLayer.push({ event: "<Event>" , ...})`), then check the resulting');
L.push('`interact` call: `eventType: web.webinteraction.linkClicks`, `data.__adobe.analytics` exactly as listed, and **no');
L.push('leftover fields from the previous row** (shared variable residue).');
L.push('');
L.push('| ✓ | Rule | Push event | linkName / linkType | events | eVars ← source |');
L.push('|---|---|---|---|---|---|');
for (const it of events.interactions) {
  L.push(`| ☐ | ${it.rule} | \`${it.acdlEvent}\` | \`${it.linkName}\` / \`${it.linkType}\` | ${evList(it.events)} | ${eVarList(it.eVars)} |`);
}
L.push('');
L.push(`## 3. Site error — \`${se.rule}\``);
L.push('');
L.push(`- [ ] Trigger: visit a 404 URL (push \`${se.acdlEvent}\`) → events \`${evList(se.analytics.events)}\` · ${eVarList(se.analytics.eVars)}`);
L.push('');
L.push('## 4. Consent');
L.push('');
L.push('- [ ] `Consent Selection` (tracking): choosing in the banner sends the interaction beacon per the table above');
L.push('- [ ] `Consent - Apply Visitor Choice`: the SAME banner choice also produces an alloy `setConsent` call whose');
L.push('      general value matches `%consent-generalValue%` mapping (opt-out strings → `out`, else `in` — MANUAL-STEPS #6)');
L.push('- [ ] After an `out` choice: subsequent interactions send NO edge calls until consent changes');
L.push('');
if (nt) {
  L.push('## 5. Newsletter test (carried natively — 5 points)');
  L.push('');
  L.push(`- [ ] (a) Page-view request carries \`decisionScopes: ["${nt.scope}"]\` and there is NO separate per-page personalization call`);
  L.push(`- [ ] (b) When Target returns the scope: \`${nt.siteContract.propositionGlobal}\` is set and CustomEvent \`${nt.siteContract.flagEvent}\` fires with \`${nt.siteContract.flagName}\` + the variant`);
  L.push(`- [ ] (c) Rendering the variant (\`${nt.siteContract.displaySelector}\` present) sends ONE \`decisioning.propositionDisplay\` whose propositions contain ONLY the newsletter proposition`);
  L.push(`- [ ] (d) Submitting the form (\`${nt.siteContract.signupDomEvent}\`) sends ONE \`decisioning.propositionInteract\` named \`newsletter:confirmation:<placement>\``);
  L.push('- [ ] (e) A visitor NOT in the test: no flag event, no display/interact sends, no console errors');
  L.push('');
}
L.push('## 6. Residue test (shared `data-interaction` variable)');
L.push('');
L.push('- [ ] On one page WITHOUT navigating: trigger Form Start, then Scroll 25. The scroll beacon must NOT carry the');
L.push('      form eVars (eVar10/eVar19) — if it does, the Update variable actions are missing their clear/remove entries');
L.push('');
L.push('## 7. Click-collection cross-check (dev-only, optional)');
L.push('');
L.push('- [ ] Per RUNBOOK Phase 4: temporarily enable SDK click collection on a Development-only build, reconcile');
L.push('      auto-collected download/exit clicks against `event16`/redirect events, then DISABLE and rebuild before promote');
L.push('');
L.push('## 8. Finding 1 re-grade evidence (collect while testing)');
L.push('');
L.push('- [ ] Zero `/b/ss/` requests across the whole session (screenshot the empty network filter)');
L.push('- [ ] `s_gpv`/`s_vnc365`/`s_nr30` cookies ARE written — by the Common Web SDK Plugins elements, not AppMeasurement');
L.push('- [ ] Old property\'s production build resources contain no classic Analytics extension (Phase 1 snapshot)');
L.push('');
L.push('## 9. Before production (gate)');
L.push('');
L.push(`- [ ] TLS end-to-end on \`https://${edgeDomain}\` — valid Adobe-served cert, no warnings (MANUAL-STEPS #4)`);
L.push('- [ ] `node scripts/verify-entry.mjs` exits PASSED (machine-diff of the hand-entered property vs the blueprint)');
L.push('- [ ] Cutover smoke test + date documentation per RUNBOOK Phase 5');
L.push('');

const outPath = join(ROOT, 'docs', 'QA-CHECKLIST.md');
await writeFile(outPath, `${L.join('\n')}\n`, 'utf8');
console.log(`QA checklist written: ${outPath}`);
console.log(`  interactions: ${events.interactions.length} · newsletter: ${nt ? 'included' : 'n/a'} · edge: ${edgeDomain}`);
