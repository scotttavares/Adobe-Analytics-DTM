#!/usr/bin/env node
// =============================================================================
// generate-build-sheet.mjs — blueprint → human build sheet for MANUAL entry
// =============================================================================
//
// Emits docs/MANUAL-BUILD-SHEET.md from the generated blueprint: every data
// element and rule as an ordered, copy-paste-ready checklist for the Data
// Collection UI. The catalog remains the single source of truth — a human
// keys it in, but never composes payloads by hand (the Finding 9 guarantee,
// manual edition). Re-run after every re-generate of the blueprint.
//
// USAGE: node scripts/generate-build-sheet.mjs
//        [--blueprint blueprint/aboutamazon-websdk.blueprint.json]
//        [--out docs/MANUAL-BUILD-SHEET.md]
// =============================================================================

import process from 'node:process';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const SENTINEL = 'CONFIRM-VIA-EXPORT';

function parseArgs(argv) {
  const values = {};
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i].startsWith('--') && argv[i + 1] && !argv[i + 1].startsWith('--')) {
      values[argv[i].slice(2)] = argv[i + 1];
      i += 1;
    }
  }
  return values;
}

const flags = (de) =>
  `force lowercase: **${de.forceLowerCase ? 'ON' : 'off'}** · clean text: **${de.cleanText ? 'ON' : 'off'}**` +
  `${de.defaultValue !== undefined && de.defaultValue !== null ? ` · default value: \`${de.defaultValue}\`` : ''}` +
  ` · storage duration: None`;

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const bpPath = args.blueprint || join(ROOT, 'blueprint', 'aboutamazon-websdk.blueprint.json');
  const outPath = args.out || join(ROOT, 'docs', 'MANUAL-BUILD-SHEET.md');
  const bp = JSON.parse(await readFile(bpPath, 'utf8'));

  const des = bp.dataElements;
  const byDelegate = (id) => des.filter((d) => d.delegate_descriptor_id === id);
  const acdl = des.filter((d) => d.extension === 'adobe-client-data-layer');
  const qsp = byDelegate('core::dataElements::query-string-parameter');
  const pageInfo = byDelegate('core::dataElements::page-info');
  const plugins = des.filter((d) => d.extension === 'common-web-sdk-plugins');
  const variables = byDelegate('adobe-alloy::dataElements::variable');
  const customCode = byDelegate('core::dataElements::custom-code');
  const payloadNames = new Set(
    customCode.filter((d) => d.name.startsWith('data-') || d.name === 'consent-generalValue').map((d) => d.name),
  );
  const utilityCode = customCode.filter((d) => !payloadNames.has(d.name));
  const builders = customCode.filter((d) => payloadNames.has(d.name));

  const L = [];
  L.push('# Manual build sheet — AboutAmazon-US (WebSDK)');
  L.push('');
  L.push('> GENERATED by `scripts/generate-build-sheet.mjs` from the blueprint — do not hand-edit.');
  L.push('> Re-run the generator whenever the catalog/blueprint changes.');
  L.push('');
  L.push('Work top to bottom. **Copy names and values exactly** (payloads reference data');
  L.push('elements by name at runtime — a typo builds green and collects nothing).');
  L.push('Prereqs already done: property, 4 extensions, library `20260728 - v1.0`.');
  L.push('');
  L.push(`Totals: **${des.length} data elements**, **${bp.rules.length} rules**.`);
  L.push('');
  L.push('---');
  L.push('');
  L.push('## 1. Data elements — Adobe Client Data Layer (Datalayer Computed State)');
  L.push('');
  L.push(`All ${acdl.length} below: extension **Adobe Client Data Layer**, type **Datalayer Computed State**.`);
  L.push('`[data layer path]` goes in the path field. Storage duration **None** for every element in this sheet.');
  L.push('');
  L.push('| # | Name | Data layer path | Force lowercase | Clean text | Default |');
  L.push('|---|---|---|---|---|---|');
  acdl.forEach((d, i) => {
    L.push(
      `| ${i + 1} | \`${d.name}\` | \`${d.settings.path}\` | ${d.forceLowerCase ? '✅' : '—'} | ${d.cleanText ? '✅' : '—'} | ${d.defaultValue ? `\`${d.defaultValue}\`` : ''} |`,
    );
  });
  L.push('');
  L.push('## 2. Data elements — Core: Query String Parameter');
  L.push('');
  L.push('Type **Query String Parameter**, case-insensitive **ON** for all.');
  L.push('');
  L.push('| Name | Parameter | Force lowercase | Clean text |');
  L.push('|---|---|---|---|');
  qsp.forEach((d) => {
    L.push(`| \`${d.name}\` | \`${d.settings.name}\` | ${d.forceLowerCase ? '✅' : '—'} | ${d.cleanText ? '✅' : '—'} |`);
  });
  L.push('');
  L.push('## 3. Data elements — Core: Page Info');
  L.push('');
  pageInfo.forEach((d) => {
    L.push(`- \`${d.name}\` — attribute **${d.settings.attribute}** — ${flags(d)}`);
  });
  L.push('');
  L.push('## 4. Data elements — Common Web SDK Plugins');
  L.push('');
  L.push('Pick the matching plugin type for each. Where a setting is not listed, leave the default.');
  L.push('');
  plugins.forEach((d) => {
    const type = d.delegate_descriptor_id.split('::').pop();
    const settings = Object.entries(d.settings || {})
      .filter(([, v]) => v !== '' && v !== null && v !== undefined)
      .map(([k, v]) => `${k} = \`${v}\``)
      .join(', ');
    L.push(`- \`${d.name}\` — type **${type}**${settings ? ` — ${settings}` : ' — all defaults'} — ${flags(d)}`);
  });
  L.push('');
  L.push('## 5. Data elements — Core: Custom Code (utility)');
  L.push('');
  utilityCode.forEach((d) => {
    L.push(`### \`${d.name}\``);
    L.push('');
    L.push(flags(d));
    if (d._decision) L.push(`\n> DECISION: ${d._decision}`);
    L.push('');
    L.push('```javascript');
    L.push(d.settings.source);
    L.push('```');
    L.push('');
  });
  if (variables.length) {
    L.push('## 6a. Payload variables — Adobe Experience Platform Web SDK: Variable');
    L.push('');
    L.push("These are Adobe's native payload containers (the documented Analytics-migration");
    L.push('pattern). No code — the values are filled in by each rule\'s **Update variable**');
    L.push('action (section 7). Create each with: extension **Adobe Experience Platform');
    L.push('Web SDK**, type **Variable**, property to populate **Data**, solution');
    L.push('**Adobe Analytics** checked (leave Audience Manager and Target unchecked).');
    L.push('');
    for (const v of variables) {
      L.push(`- \`${v.name}\``);
    }
    L.push('');
    L.push('Notes-panel line for all three: "Adobe Web SDK Variable — the container each');
    L.push('rule fills via its Update variable action and sends to Adobe. Field mappings');
    L.push('are specified in the governed catalog (Adobe-Analytics-DTM repo)."');
    L.push('');
  }
  L.push('## 6. Data elements — Core: Custom Code (GENERATED payload builders)');
  L.push('');
  L.push('Paste each block **verbatim** — never edit by hand; the catalog + generator own these.');
  L.push('All flags: force lowercase **off**, clean text **off**, storage duration **None**.');
  L.push('');
  L.push('Add this to each element\'s **Notes** panel (business-friendly provenance — swap the');
  L.push('"What this powers" line per element, and put a real contact in the Owner line):');
  L.push('');
  L.push('```');
  L.push("Auto-generated tracking code — please don't edit on this screen.");
  L.push('Edits made here will be overwritten at the next update and can silently break');
  L.push('Amazon News reporting.');
  L.push('');
  L.push('What this powers: <one plain-English line for this element>.');
  L.push('');
  L.push('To request a tracking change: tracking definitions live in a governed');
  L.push('configuration (Adobe-Analytics-DTM repository, websdk-property folder).');
  L.push('Changes made there regenerate this code so every event stays consistent.');
  L.push('');
  L.push('Owner: analytics implementation team — contact before making any change here.');
  L.push('```');
  L.push('');
  builders.forEach((d) => {
    L.push(`### \`${d.name}\``);
    L.push('');
    L.push('```javascript');
    L.push(d.settings.source);
    L.push('```');
    L.push('');
  });
  L.push('---');
  L.push('');
  L.push('## 7. Rules');
  L.push('');
  L.push('Every rule: **one event + one action**, no conditions, event order left at the default (50).');
  L.push('');
  L.push('Event setup per rule (verified against the old property\'s UI): extension');
  L.push('**Adobe Client Data Layer**, event type **Data Pushed**, "Listen to" =');
  L.push('**Specific Event**, the **Event / Key to register for** value shown below, and');
  L.push('the **Time scope** shown (All = past + future, which catches pushes queued');
  L.push('before Launch loads — the page-view rule depends on that).');
  L.push('');
  L.push(`Where the event name still says \`${SENTINEL}\`, open the SAME-NAMED rule in the`);
  L.push('OLD AboutAmazon-US property and copy its "Event / Key to register for" value and');
  L.push('Time scope exactly. The new `Consent - Apply Visitor Choice` rule uses the same');
  L.push('event as `Consent Selection`.');
  L.push('');
  bp.rules.forEach((r, i) => {
    L.push(`### ${i + 1}. \`${r.name}\``);
    L.push('');
    const ev = r.event;
    const evName = ev.settings && ev.settings.event ? ev.settings.event : '(see settings)';
    const scope = ev.timeScope ? ev.timeScope.charAt(0).toUpperCase() + ev.timeScope.slice(1) : 'All';
    L.push(
      `- **Event**: Adobe Client Data Layer → *Data Pushed* — Listen to: Specific Event · ` +
        `Event/Key: \`${evName}\` · Time scope: **${scope}**`,
    );
    let actionNo = 0;
    const label = () => {
      actionNo += 1;
      return r.actions.length > 1 ? `**Action ${actionNo}**` : '**Action**';
    };
    for (const a of r.actions) {
      if (a.delegate_descriptor_id.endsWith('update-variable')) {
        const varName = String(a.settings.dataElementId || '').replace('RESOLVE-DE-ID:', '');
        const fields = (a.settings.data && a.settings.data.__adobe && a.settings.data.__adobe.analytics) || {};
        L.push(`- ${label()}: Web SDK → *Update variable* — variable \`${varName}\`. Set:`);
        for (const [k, v] of Object.entries(fields)) {
          L.push(`    - ${k} = \`${v}\``);
        }
        L.push('    - Use the action\'s clear/remove affordance so values from a PREVIOUS event');
        L.push('      on the same page do not linger (residue test: RUNBOOK Phase 4).');
      } else if (a.delegate_descriptor_id.endsWith('send-event')) {
        const s = a.settings;
        L.push(
          `- ${label()}: Adobe Experience Platform Web SDK → *Send event* — instance \`${s.instanceName}\`` +
            `${s.renderDecisions ? ' · **Render visual personalization decisions: ✅ ON**' : ''}` +
            ` · type \`${s.type}\` · data \`${s.data}\``,
        );
      } else if (a.delegate_descriptor_id.endsWith('set-consent')) {
        L.push(
          `- ${label()}: Adobe Experience Platform Web SDK → *Set consent* — instance \`${a.settings.instanceName}\`` +
            ` · standard **Adobe 2.0** · general = \`%${bp.dataElements.find((d) => d.name === 'consent-generalValue').name}%\``,
        );
      } else {
        L.push(`- ${label()}: \`${a.delegate_descriptor_id}\` — settings: \`${JSON.stringify(a.settings)}\``);
      }
    }
    if (r._note) L.push(`- Note: ${r._note}`);
    L.push('');
  });
  L.push('---');
  L.push('');
  L.push('## 8. Finish');
  L.push('');
  L.push('1. Library `20260728 - v1.0 - Initial Web SDK Implementation` → **Add All Changed Resources** → Save & Build for Development.');
  L.push('2. Run the Phase 4 QA pass in docs/RUNBOOK.md against the Development embed code.');
  L.push('3. Optional but recommended once credentials exist: run `scripts/export-current.mjs`');
  L.push('   against **this new property** and diff the export against the blueprint —');
  L.push('   machine-verifying the manual entry (typo hunt) before staging/production.');
  L.push('');

  await writeFile(outPath, `${L.join('\n')}\n`, 'utf8');
  const sentinels = bp.rules.filter((r) => r.event.settings && r.event.settings.event === SENTINEL).length;
  console.log(`Build sheet written: ${outPath}`);
  console.log(`  data elements: ${des.length} (ACDL ${acdl.length}, QSP ${qsp.length}, plugins ${plugins.length}, custom ${utilityCode.length}+${builders.length})`);
  console.log(`  rules: ${bp.rules.length}${sentinels ? ` — ${sentinels} event names still to copy from the OLD property (marked ${SENTINEL})` : ''}`);
}

main().catch((err) => {
  console.error(`\nFAILED: ${err.message}`);
  process.exit(1);
});
